CREATE SCHEMA IF NOT EXISTS etl;

CREATE TABLE IF NOT EXISTS etl.alma_loans (
    extraction_date date NOT NULL,
    row_number bigint NOT NULL CHECK (row_number > 0),
    loaded_at timestamp with time zone NOT NULL,
    phone_number text,
    campus_name text,
    circ_desk_name text,
    loan_date date NOT NULL,
    author text,
    barcode text,
    in_house_loan_indicator text,
    item_id text,
    item_loan_id text,
    loan_status text,
    loan_time text,
    mms_id text,
    title text,
    item_policy text,
    user_name text,
    user_primary_identifier text,
    preferred_email text,
    material_type text,
    PRIMARY KEY (extraction_date, row_number),
    CHECK (loan_date = extraction_date)
);

CREATE TABLE IF NOT EXISTS etl.alma_renewals (
    extraction_date date NOT NULL,
    row_number bigint NOT NULL CHECK (row_number > 0),
    loaded_at timestamp with time zone NOT NULL,
    campus_name text,
    author text,
    barcode text,
    item_id text,
    item_loan_id text,
    loan_status text,
    mms_id text,
    title text,
    item_policy text,
    phone_number text,
    renewal_campus_name text,
    renewal_date date NOT NULL,
    user_name text,
    material_type text,
    user_primary_identifier text,
    preferred_email text,
    renewals double precision,
    PRIMARY KEY (extraction_date, row_number),
    CHECK (renewal_date = extraction_date)
);
